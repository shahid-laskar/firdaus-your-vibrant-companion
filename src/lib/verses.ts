/** Stable per-day verse: same for the whole day, moving through the collection. */
export function verseOfDay(date = new Date()): Verse {
  const dayNumber = Math.floor(date.getTime() / 86_400_000);
  return VERSES[dayNumber % VERSES.length]!;
}
